// 门票口径：免费返回 0；有淡旺季差异时按季节取，`season` 只接受 'peak' | 'offPeak'
export const spotTicket = (spot, season = 'offPeak') => {
  const ticket = spot.ticket || {}
  if (ticket.free) return 0
  const price = season === 'peak' ? ticket.peak : ticket.offPeak
  return typeof price === 'number' ? price : 0
}

// 只在淡季与旺季价格不同时才提示两种价格，避免页面上出现「40 元 / 40 元」
export const hasSeasonPrice = (spot) => {
  const ticket = spot.ticket || {}
  return typeof ticket.peak === 'number' && ticket.peak !== ticket.offPeak
}
